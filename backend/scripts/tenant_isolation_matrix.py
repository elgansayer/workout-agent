@contextmanager
def _production_tenancy() -> Iterator[None]:
    """Run the probes with the production tenancy policy (no shared tenant)."""
    saved = {
        key: os.environ.get(key)
        for key in ("APP_ENV", "ALLOW_ANONYMOUS_WEB", "ENCRYPTION_KEY")
    }
    os.environ["APP_ENV"] = "production"
    os.environ["ALLOW_ANONYMOUS_WEB"] = "0"
    if not os.environ.get("ENCRYPTION_KEY"):
        from cryptography.fernet import Fernet

        os.environ["ENCRYPTION_KEY"] = Fernet.generate_key().decode()
    try:
        yield
    finally:
        for key, value in saved.items():
            if value is None:
                os.environ.pop(key, None)
            else:
                os.environ[key] = value


def _make_world(db_path: str) -> World:
    init_db(db_path)
    alice = database.get_or_create_user(
        "matrix-alice@example.test", "Matrix Alice", db_path
    )["id"]
    bob = database.get_or_create_user(
        "matrix-bob@example.test", "Matrix Bob", db_path
    )["id"]
    return World(db=str(db_path), alice=str(alice), bob=str(bob), vault=SecretVault(db_path))


def _insert_owned_row(conn: sqlite3.Connection, table: str, user_id: str) -> int:
    """Insert one syntactically valid synthetic row and return its rowid."""
    names: list[str] = []
    values: list[Any] = []
    for _cid, name, column_type, _notnull, _default, pk in conn.execute(
        f"PRAGMA table_info({table})"
    ).fetchall():
        if name == "user_id":
            names.append(name)
            values.append(user_id)
        elif pk and column_type.upper() == "INTEGER" and name == "id":
            continue  # rowid alias
        elif column_type.upper() == "INTEGER":
            names.append(name)
            values.append(1)
        elif column_type.upper() == "REAL":
            names.append(name)
            values.append(1.0)
        else:
            names.append(name)
            values.append("synthetic")
    placeholders = ", ".join("?" for _ in names)
    cursor = conn.execute(
        f"INSERT INTO {table} ({', '.join(names)}) VALUES ({placeholders})", values
    )
    if cursor.lastrowid is None:  # pragma: no cover - SQLite always returns it
        raise RuntimeError(f"could not seed {table}")
    return int(cursor.lastrowid)


def _seed_generic(world: World) -> dict[str, tuple[int, int]]:
    """Give each tenant one row per table and return ``(alice, bob)`` rowids."""
    rowids: dict[str, tuple[int, int]] = {}
    with database.transaction(world.db) as conn:
        for table in GENERIC_TABLES:
            alice_row = _insert_owned_row(conn, table, world.alice)
            bob_row = _insert_owned_row(conn, table, world.bob)
            rowids[table] = (alice_row, bob_row)
    return rowids


