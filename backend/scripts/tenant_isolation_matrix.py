def _queue_probe(world: World) -> Cell:
    seen: list[str] = []

    def work(owner: OwnerIdentity) -> str:
        seen.append(owner.user_id)
        return owner.user_id

    outcomes = [
        run_owned_job(OwnedJob("matrix-sync", OwnerIdentity(uid)), world.db, work)
        for uid in (world.alice, world.bob)
    ]
    forged = run_owned_job(
        OwnedJob("matrix-sync", OwnerIdentity("matrix-unknown")), world.db, work
    )
    if [outcome.status for outcome in outcomes] != [JobStatus.COMPLETED] * 2:
        return Cell("Background job queue", "queue", Result.FAIL, "A real owner job was not completed")
    if seen != [world.alice, world.bob]:
        return Cell(
            "Background job queue",
            "queue",
            Result.FAIL,
            "Job work observed an identity other than its own owner",
        )
    if forged.status is not JobStatus.DENIED or len(seen) != 2:
        return Cell(
            "Background job queue",
            "queue",
            Result.FAIL,
            "An unregistered owner was allowed to run work",
        )
    return Cell(
        "Background job queue",
        "queue",
        Result.PASS,
        "Each job received its own owner; an unknown owner was denied before work",
    )


def _cache_probe(world: World) -> list[Cell]:
    alice_key = owner_scoped_key(OwnerIdentity(world.alice), "matrix-cache", "plan")
    bob_key = owner_scoped_key(OwnerIdentity(world.bob), "matrix-cache", "plan")
    cache: dict[str, str] = {}
    cache[alice_key] = "alice-plan"
    read = Cell(
        "Owner-scoped caches",
        "read",
        Result.PASS if alice_key != bob_key and bob_key not in cache else Result.FAIL,
        "Owner is a key segment; Alice's cache entry is unreachable from Bob's key",
    )
    cache[bob_key] = "bob-plan"
    change = Cell(
        "Owner-scoped caches",
        "change",
        Result.PASS
        if cache.get(alice_key) == "alice-plan" and cache.get(bob_key) == "bob-plan"
        else Result.FAIL,
        "Writing Bob's cache key leaves Alice's entry untouched",
    )
    return [read, change]


def _cursor_probe(world: World) -> list[Cell]:
    alice_key = owner_scoped_key(
        OwnerIdentity(world.alice), "connector-cursor", "google_health"
    )
    bob_key = owner_scoped_key(
        OwnerIdentity(world.bob), "connector-cursor", "google_health"
    )
    cursor = {
        alice_key: "alice-cursor-token",
        bob_key: "bob-cursor-token",
    }
    read = Cell(
        "Connector sync cursors",
        "read",
        Result.PASS
        if alice_key != bob_key and cursor[alice_key] == "alice-cursor-token"
        else Result.FAIL,
        "Cursor keys bind the owner; Alice reads back only her own cursor value",
    )
    cursor[alice_key] = "alice-advanced"
    change = Cell(
        "Connector sync cursors",
        "change",
        Result.PASS
        if cursor[bob_key] == "bob-cursor-token"
        and cursor[alice_key] == "alice-advanced"
        else Result.FAIL,
        "Advancing Alice's cursor cannot move Bob's",
    )
    return [read, change]


def _context_probe(world: World) -> Cell:
    contexts: dict[str, str] = {}

    def work(owner: OwnerIdentity) -> str:
        context = OwnedContext(owner, "matrix-ai", {"owner": owner.user_id})
        contexts[owner.user_id] = context.owner.user_id
        return context.owner.user_id

    run_owned_job(OwnedJob("matrix-ai", OwnerIdentity(world.alice)), world.db, work)
    run_owned_job(OwnedJob("matrix-ai", OwnerIdentity(world.bob)), world.db, work)
    if contexts != {world.alice: world.alice, world.bob: world.bob}:
        return Cell(
            "AI contexts",
            "receive",
            Result.FAIL,
            "An AI context was persisted under a different owner",
        )
    return Cell(
        "AI contexts",
        "receive",
        Result.PASS,
        "Each AI context carries the owner whose data produced it",
    )


