def _session_probe(world: World) -> list[Cell]:
    with database.transaction(world.db) as conn:
        database.ensure_user_sessions_schema(conn)
    with database.transaction(world.db) as conn:
        for token, user_id in (
            ("matrix-session-alice", world.alice),
            ("matrix-session-bob", world.bob),
        ):
            conn.execute(
                "INSERT OR REPLACE INTO user_sessions "
                "(session_token_hash, user_id, created_at, last_seen_at) "
                "VALUES (?, ?, 0, 0)",
                (token, user_id),
            )
    with database.transaction(world.db) as conn:
        alice_sessions = {
            row[0]
            for row in conn.execute(
                "SELECT session_token_hash FROM user_sessions WHERE user_id = ?",
                (world.alice,),
            ).fetchall()
        }
    read = Cell(
        "Browser sessions",
        "read",
        Result.PASS
        if alice_sessions == {"matrix-session-alice"}
        else Result.FAIL,
        "Session lookup is owner-scoped; Alice cannot enumerate Bob's session",
    )

    revoke_account_sessions(world.bob, world.db)
    with database.transaction(world.db) as conn:
        epochs = {
            row[0]: int(row[1])
            for row in conn.execute(
                "SELECT id, session_epoch FROM users WHERE id IN (?, ?)",
                (world.alice, world.bob),
            ).fetchall()
        }
    change = Cell(
        "Browser sessions",
        "change",
        Result.PASS
        if epochs[world.alice] == 0 and epochs[world.bob] == 1
        else Result.FAIL,
        "Revoking Bob's sessions advances only Bob's session epoch",
    )
    return [read, change]


def _notification_probe(world: World) -> list[Cell]:
    alice_id = save_notification(
        world.alice, "Alice title", "alice-body", db_path=world.db
    )
    bob_id = save_notification(world.bob, "Bob title", "bob-body", db_path=world.db)
    save_push_subscription(
        world.alice,
        "https://push.example.test/alice",
        "alice-p256dh",
        "alice-auth",
        world.db,
    )
    save_push_subscription(
        world.bob,
        "https://push.example.test/bob",
        "bob-p256dh",
        "bob-auth",
        world.db,
    )

    alice_notifications = {item["id"] for item in get_notifications(world.alice, db_path=world.db)}
    read = Cell(
        "Notifications and push delivery",
        "read",
        Result.PASS
        if alice_notifications == {alice_id}
        else Result.FAIL,
        "Alice's notification query returns only her notification",
    )

    changed = mark_notification_read(bob_id, world.alice, world.db)
    still_unread = get_unread_notification_count(world.bob, world.db) == 1
    change = Cell(
        "Notifications and push delivery",
        "change",
        Result.PASS if changed is False and still_unread else Result.FAIL,
        "Alice cannot mark Bob's notification read",
    )

    bob_pushes = {item["endpoint"] for item in get_push_subscriptions(world.bob, world.db)}
    alice_pushes = {item["endpoint"] for item in get_push_subscriptions(world.alice, world.db)}
    receive = Cell(
        "Notifications and push delivery",
        "receive",
        Result.PASS
        if alice_pushes == {"https://push.example.test/alice"}
        and bob_pushes == {"https://push.example.test/bob"}
        else Result.FAIL,
        "Push subscriptions resolve per owner; Alice never receives Bob's endpoint",
    )
    return [read, change, receive]


def _credential_probes(world: World) -> list[Cell]:
    vault = world.vault
    vault.store(world.alice, "openai", api_key="synthetic-alice-ai-key")
    vault.store(world.bob, "claude", api_key="synthetic-bob-ai-key")
    vault.store(world.alice, "hevy", api_key="synthetic-alice-hevy-key")
    vault.store(world.bob, "hevy", api_key="synthetic-bob-hevy-key")

    ai_read = _secret_read_cell(
        vault,
        world,
        surface="AI provider credentials",
        alice_provider="openai",
        expected_alice="synthetic-alice-ai-key",
        bob_provider="claude",
        expected_bob="synthetic-bob-ai-key",
    )
    connector_read = _secret_read_cell(
        vault,
        world,
        surface="Connector credentials",
        alice_provider="hevy",
        expected_alice="synthetic-alice-hevy-key",
        bob_provider="hevy",
        expected_bob="synthetic-bob-hevy-key",
    )

    # Rotation by Alice must leave Bob's key intact.
    vault.rotate(world.alice, "hevy", api_key="synthetic-alice-hevy-rotated")
    bob_hevy = _reveal(vault, world.bob, "hevy")
    ai_change = Cell(
        "AI provider credentials",
        "change",
        Result.PASS
        if _reveal(vault, world.bob, "claude") == "synthetic-bob-ai-key"
        else Result.FAIL,
        "Bob's AI key is unchanged by Alice's credential operations",
    )
    connector_change = Cell(
        "Connector credentials",
        "change",
        Result.PASS if bob_hevy == "synthetic-bob-hevy-key" else Result.FAIL,
        "Rotating Alice's connector key does not touch Bob's",
    )

    # Revocation is owner-scoped too.
    vault.revoke(world.alice, "hevy")
    revoked_isolation = _reveal(vault, world.bob, "hevy") == "synthetic-bob-hevy-key"
    if not revoked_isolation:
        connector_change = Cell(
            "Connector credentials",
            "change",
            Result.FAIL,
            "Revoking Alice's connector key affected Bob's",
        )

    # Audit events are owner-scoped: Alice only sees her own provider history.
    alice_events = vault.recent_events(world.alice)
    alice_providers = {event.provider for event in alice_events}
    audit = Cell(
        "Credential audit trail",
        "read",
        Result.PASS
        if "claude" not in alice_providers and "openai" in alice_providers
        else Result.FAIL,
        "Alice's audit page contains only her credential events",
    )
    if not revoked_isolation:
        audit = Cell(
            "Credential audit trail",
            "read",
            Result.FAIL,
            "Isolation of the credential audit trail could not be proven",
        )
    return [ai_read, ai_change, connector_read, connector_change, audit]


def _reveal(vault: SecretVault, user_id: str, provider: str) -> str | None:
    try:
        credential = vault.resolve(user_id, provider, purpose="matrix")
    except CredentialUnavailableError:
        return None
    return credential.api_key.reveal() if credential.api_key is not None else None


def _secret_read_cell(
    vault: SecretVault,
    world: World,
    *,
    surface: str,
    alice_provider: str,
    expected_alice: str,
    bob_provider: str,
    expected_bob: str,
) -> Cell:
    alice_value = _reveal(vault, world.alice, alice_provider)
    bob_value = _reveal(vault, world.bob, bob_provider)
    if alice_value != expected_alice or bob_value != expected_bob:
        return Cell(surface, "read", Result.FAIL, "A stored secret crossed tenants")
    if alice_provider != bob_provider:
        try:
            vault.resolve(world.alice, bob_provider, purpose="matrix-cross-tenant")
        except CredentialUnavailableError:
            pass
        else:
            return Cell(
                surface,
                "read",
                Result.FAIL,
                "Alice resolved a provider only Bob has stored",
            )
    # Secret material must never appear in the browser-facing summaries.
    summary = json.dumps(
        {
            key: value.to_public_dict()
            for key, value in vault.list_credentials(world.alice).items()
        },
        sort_keys=True,
    )
    if expected_alice in summary or expected_bob in summary:
        return Cell(surface, "read", Result.FAIL, "A summary exposed secret material")
    return Cell(
        surface,
        "read",
        Result.PASS,
        "Resolve returns only the caller's secret; Alice cannot resolve Bob's provider",
    )


