def _export_probe(world: World) -> Cell:
    """An export assembled from scoped reads contains only the caller's rows."""
    with database.transaction(world.db) as conn:
        bob_rowids = {
            table: {
                row[0]
                for row in conn.execute(
                    f"SELECT rowid FROM {table} WHERE user_id = ?", (world.bob,)
                ).fetchall()
            }
            for table in USER_OWNED_TABLES
        }
        envelope: dict[str, list[int]] = {}
        for table in USER_OWNED_TABLES:
            envelope[table] = [
                int(row[0])
                for row in conn.execute(
                    f"SELECT rowid FROM {table} WHERE user_id = ?", (world.alice,)
                ).fetchall()
            ]
    json.dumps(envelope, sort_keys=True)  # exports are JSON-serialisable
    # Compare the actual scoped sets; a substring check would be meaningless
    # because small rowids appear in every table.
    leaked = any(
        set(envelope[table]) & bob_rowids[table] for table in USER_OWNED_TABLES
    )
    if leaked:
        return Cell(
            "User data export",
            "export",
            Result.FAIL,
            "Alice's export envelope contained a Bob rowid",
        )
    return Cell(
        "User data export",
        "export",
        Result.PASS,
        "Export envelope built only from Alice-scoped reads; no Bob rowid present",
    )


