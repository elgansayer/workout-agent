"""Generate the tenant-isolation matrix from live probes.

The matrix answers one question for every user-owned surface: can user A read,
change, export, queue or receive user B's data?  Each cell is not documentation
copied from a test; it is produced by running two synthetic tenants against a
throwaway SQLite database and trying the cross-tenant operation.

The Markdown under ``docs/TENANT_ISOLATION_MATRIX.md`` is generated output.
Regenerate it with::

    python backend/scripts/tenant_isolation_matrix.py

``--check`` fails when the committed document is stale or when a probe fails, so
a new user-owned table cannot silently ship without an isolation proof.

The probe assertions are deliberately narrow: they prove the production
repositories/vault/worker guards keep the tenants apart at the persistence
boundary.  They are not a substitute for the focused suites listed in
``docs/TENANT_ISOLATION.md``.
"""

