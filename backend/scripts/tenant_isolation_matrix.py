def _read_probe(world: World, table: str, rowids: tuple[int, int]) -> Cell:
    alice_rowid, bob_rowid = rowids
    with database.transaction(world.db) as conn:
        visible = {
            row[0]
            for row in conn.execute(
                f"SELECT rowid FROM {table} WHERE user_id = ?", (world.alice,)
            ).fetchall()
        }
        bob_rows = {
            row[0]
            for row in conn.execute(
                f"SELECT rowid FROM {table} WHERE user_id = ?", (world.bob,)
            ).fetchall()
        }
    if (
        visible != {alice_rowid}
        or bob_rowid in visible
        or bob_rows != {bob_rowid}
    ):
        return Cell(table, "read", Result.FAIL, "Alice's scoped query saw Bob's row")
    return Cell(
        table,
        "read",
        Result.PASS,
        "Alice sees only her rowid; Bob sees only his; neither sees the other",
    )


def _change_probe(world: World, table: str, rowids: tuple[int, int]) -> Cell:
    _alice_rowid, bob_rowid = rowids
    with database.transaction(world.db) as conn:
        # A request that knows Bob's record id but is authenticated as Alice must
        # match zero rows, and must not remove or rewrite Bob's row.
        changed = conn.execute(
            f"UPDATE {table} SET user_id = user_id WHERE rowid = ? AND user_id = ?",
            (bob_rowid, world.alice),
        ).rowcount
        removed = conn.execute(
            f"DELETE FROM {table} WHERE rowid = ? AND user_id = ?",
            (bob_rowid, world.alice),
        ).rowcount
        still_there = conn.execute(
            f"SELECT count(*) FROM {table} WHERE rowid = ? AND user_id = ?",
            (bob_rowid, world.bob),
        ).fetchone() == (1,)
    if changed or removed or not still_there:
        return Cell(table, "change", Result.FAIL, "Alice altered Bob's row")
    return Cell(
        table,
        "change",
        Result.PASS,
        "Alice-scoped UPDATE/DELETE matched no rows; Bob's row survived",
    )


