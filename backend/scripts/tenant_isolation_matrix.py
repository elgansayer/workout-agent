def _special_cells(world: World) -> list[Cell]:
    # Seed the bespoke surfaces before exporting so the export probe sees the
    # notification, subscription and credential rows too.
    cells: list[Cell] = []
    cells.extend(_notification_probe(world))
    cells.extend(_credential_probes(world))
    cells.extend(_session_probe(world))
    cells.append(_export_probe(world))
    cells.append(_queue_probe(world))
    cells.extend(_cache_probe(world))
    cells.extend(_cursor_probe(world))
    cells.append(_context_probe(world))
    return cells


def build_matrix(db_path: str | None = None) -> list[Cell]:
    """Run every probe and return the resulting cells."""
    cleanup = False
    if db_path is None:
        handle, db_path = tempfile.mkstemp(prefix="tenant-matrix-", suffix=".db")
        os.close(handle)
        cleanup = True
    try:
        with _production_tenancy():
            world = _make_world(db_path)
            rowids = _seed_generic(world)
            cells: list[Cell] = []
            for table in GENERIC_TABLES:
                cells.append(_read_probe(world, table, rowids[table]))
                cells.append(_change_probe(world, table, rowids[table]))
            cells.extend(_special_cells(world))
            return cells
    finally:
        if cleanup:
            for suffix in ("", "-wal", "-shm"):
                Path(f"{db_path}{suffix}").unlink(missing_ok=True)


def _surface_order(cells: list[Cell]) -> list[str]:
    order: list[str] = []
    for cell in cells:
        if cell.surface not in order:
            order.append(cell.surface)
    return sorted(order)


def render_markdown(cells: list[Cell]) -> str:
    """Render the deterministic Markdown matrix."""
    by_surface: dict[str, dict[str, Cell]] = {}
    for cell in cells:
        by_surface.setdefault(cell.surface, {})[cell.operation] = cell

    lines = [
        "# Tenant-isolation matrix",
        "",
        GENERATED_NOTICE,
        "",
        "Generated by running two synthetic tenants (`matrix-alice` and",
        "`matrix-bob`) against a throwaway SQLite database and attempting each",
        "cross-tenant operation through production code. Do not edit by hand;",
        "regenerate with `python backend/scripts/tenant_isolation_matrix.py`.",
        "",
        "A **PASS** cell means user A could not read, change, export, queue or",
        "receive user B's data for that surface. **N/A** means the operation does",
        "not apply to that surface.",
        "",
        "| Surface | Read | Change | Export | Queue | Receive |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for surface in _surface_order(cells):
        row = by_surface[surface]
        rendered = [
            row[operation].result.value if operation in row else Result.NA.value
            for operation in OPERATIONS
        ]
        lines.append(f"| {surface} | " + " | ".join(rendered) + " |")

    lines.extend(
        [
            "",
            "## Probe detail",
            "",
            "| Surface | Operation | Result | Probe |",
            "| --- | --- | --- | --- |",
        ]
    )
    for surface in _surface_order(cells):
        for operation in OPERATIONS:
            detail = by_surface[surface].get(operation)
            if detail is None:
                continue
            lines.append(
                f"| {detail.surface} | {detail.operation} | {detail.result.value} | "
                f"{detail.probe} |"
            )
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero when a probe fails or the committed document is stale",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help=(
            "document path; defaults to "
            f"{DEFAULT_OUTPUT.relative_to(REPO_ROOT)} for markdown and stdout for json"
        ),
    )
    parser.add_argument(
        "--format",
        choices=("markdown", "json"),
        default="markdown",
        help="write the readable matrix or the raw cell list",
    )
    args = parser.parse_args(argv)

    cells = build_matrix()
    failures = [cell for cell in cells if cell.result is Result.FAIL]

    if args.format == "json":
        payload = [
            {
                "surface": cell.surface,
                "operation": cell.operation,
                "result": cell.result.value,
                "probe": cell.probe,
            }
            for cell in cells
        ]
        rendered = json.dumps(payload, indent=2, sort_keys=True) + "\n"
        output = args.output
    else:
        rendered = render_markdown(cells)
        output = args.output or DEFAULT_OUTPUT

    if args.check:
        if failures:
            for cell in failures:
                print(
                    f"FAIL {cell.surface} / {cell.operation}: {cell.probe}",
                    file=sys.stderr,
                )
            return 1
        if args.format == "markdown":
            current = output.read_text(encoding="utf-8") if output.exists() else ""
            if current != rendered:
                print(
                    f"{output} is stale; regenerate with "
                    "python backend/scripts/tenant_isolation_matrix.py",
                    file=sys.stderr,
                )
                return 1
        return 0

    if output is None:
        sys.stdout.write(rendered)
    else:
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(rendered, encoding="utf-8")
        print(f"Wrote {output} ({len(cells)} cells, {len(failures)} failure(s)).")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
