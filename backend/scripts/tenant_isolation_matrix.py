OPERATIONS = ("read", "change", "export", "queue", "receive")
GENERATED_NOTICE = "<!-- generated by backend/scripts/tenant_isolation_matrix.py -->"

# Surfaces probed through bespoke code rather than the generic persistence sweep.
BESPOKE_TABLES = frozenset(
    {
        "notifications",
        "push_subscriptions",
        "user_api_keys",
    }
)
# Every table name below comes from the ``database.USER_OWNED_TABLES`` code
# constant (never client input), so it is safe to interpolate into the probe
# SQL. Every value remains parameterised.
GENERIC_TABLES = tuple(
    table for table in USER_OWNED_TABLES if table not in BESPOKE_TABLES
)


class Result(StrEnum):
    PASS = "PASS"
    FAIL = "FAIL"
    NA = "N/A"


@dataclass(frozen=True)
class Cell:
    surface: str
    operation: str
    result: Result
    probe: str


@dataclass(frozen=True)
class World:
    db: str
    alice: str
    bob: str
    vault: SecretVault


