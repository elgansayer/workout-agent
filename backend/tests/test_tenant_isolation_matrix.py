"""Deterministic proof of the generated tenant-isolation matrix.

The matrix document is generated by running two synthetic tenants through the
real repositories, export assembly, worker guards, session registry, notification
delivery and secret vault. These tests fail when a probe stops proving isolation,
when a user-owned surface loses coverage, or when the committed document drifts
from the code.
"""

from __future__ import annotations

import os
import sqlite3
import tempfile
from pathlib import Path

import pytest
from database import USER_OWNED_TABLES, init_db
from legacy_ownership import NOT_TRANSFERRED_TABLES
from scripts import tenant_isolation_matrix as matrix


@pytest.fixture(scope="module")
def cells() -> list[matrix.Cell]:
    handle, path = tempfile.mkstemp(prefix="matrix-test-", suffix=".db")
    os.close(handle)
    try:
        return matrix.build_matrix(path)
    finally:
        for suffix in ("", "-wal", "-shm"):
            Path(f"{path}{suffix}").unlink(missing_ok=True)


def test_every_probe_passes(cells: list[matrix.Cell]) -> None:
    failures = [
        f"{cell.surface} / {cell.operation}: {cell.probe}"
        for cell in cells
        if cell.result is matrix.Result.FAIL
    ]
    assert failures == []


def test_the_matrix_exercises_every_operation(cells: list[matrix.Cell]) -> None:
    assert {cell.operation for cell in cells} == set(matrix.OPERATIONS)
    for operation in matrix.OPERATIONS:
        assert any(
            cell.operation == operation and cell.result is matrix.Result.PASS
            for cell in cells
        ), operation


def test_every_user_owned_table_is_proven(cells: list[matrix.Cell]) -> None:
    surfaces = {cell.surface for cell in cells}
    for table in USER_OWNED_TABLES:
        expected = (
            "Notifications and push delivery"
            if table in {"notifications", "push_subscriptions"}
            else "AI provider credentials"
            if table == "user_api_keys"
            else table
        )
        assert expected in surfaces, table


def test_discovered_user_tables_are_all_covered(tmp_path: Path) -> None:
    db = str(tmp_path / "schema.db")
    with matrix._production_tenancy():
        init_db(db)
    with sqlite3.connect(db) as conn:
        discovered = {
            row[0]
            for row in conn.execute(
                "SELECT m.name FROM sqlite_master m "
                "JOIN pragma_table_info(m.name) c "
                "WHERE m.type = 'table' AND c.name = 'user_id'"
            ).fetchall()
        }
    untransferred = set(NOT_TRANSFERRED_TABLES) & discovered
    assert discovered == set(USER_OWNED_TABLES) | untransferred


def test_committed_matrix_is_current(cells: list[matrix.Cell]) -> None:
    rendered = matrix.render_markdown(cells)
    committed = matrix.DEFAULT_OUTPUT.read_text(encoding="utf-8")
    assert committed == rendered, (
        "docs/TENANT_ISOLATION_MATRIX.md is stale; regenerate it with "
        "python backend/scripts/tenant_isolation_matrix.py"
    )


def test_a_failed_probe_is_visible_in_the_document() -> None:
    rendered = matrix.render_markdown(
        [matrix.Cell("example", "read", matrix.Result.FAIL, "synthetic leak")]
    )
    assert "| example | FAIL |" in rendered
    assert "synthetic leak" in rendered
